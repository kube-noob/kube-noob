#!/usr/bin/env python3
"""Generate docs/mcp-tool-profiles.md from kube_noob.tool_profiles and the tool surface itself.

Usage: python scripts/tool_profiles_doc.py            rewrite the document
       python scripts/tool_profiles_doc.py --check    exit 1 when it is stale

The document is the answer to "which tools does --tools incident give me?", and a hand-written answer to that goes
stale the first time a tool is added -- which is exactly the defect docs/compliance.md had when its heading said
"The 78 audit rules" with 89 in the code (G206). So every tool name, every count and every one-line purpose below
comes from the code, and tests/test_tool_profiles.py::test_the_document_and_the_code_agree fails when they differ.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from kube_noob import tool_profiles  # noqa: E402
from kube_noob.config import Settings  # noqa: E402
from kube_noob.server.mcp_app import TOOL_PREFIX  # noqa: E402
from kube_noob.toolkit import Toolkit  # noqa: E402

DOC = ROOT / "docs" / "mcp-tool-profiles.md"


def _settings(*, everything: bool) -> Settings:
    s = Settings()
    if everything:
        s.cluster.enabled = True
        s.web_enabled = True
        s.rhacs.enabled = True
        s.memory.paths = [str(ROOT)]
    return s


def _specs(*, everything: bool) -> dict[str, str]:
    return {spec.name: spec.title for spec in Toolkit(_settings(everything=everything)).specs()}


def render() -> str:
    default = _specs(everything=False)
    everything = _specs(everything=True)
    named = [n for n in tool_profiles.NAMES if n != tool_profiles.ALL]
    lines = [
        "<!-- Generated by scripts/tool_profiles_doc.py. Do not edit: run the script. -->",
        "",
        "# MCP tool profiles",
        "",
        f"The MCP server offers {len(default)} tools in its default configuration and {len(everything)} across "
        "every optional surface (live cluster, web, RHACS Central, team memory). A client reads all of their "
        "schemas before it calls any of them, so the whole surface costs context a model also needs for the "
        "user's own manifests. `--tools PROFILE` narrows it to a named set:",
        "",
        "```bash",
        "kube-noob mcp --tools incident",
        "```",
        "",
        "`--tools all` is the default and is exactly the surface the server had before profiles existed. The same "
        "choice is available to any host that cannot pass a flag, as `KUBE_NOOB_MCP_TOOLS` or `server.tools` in "
        "the configuration file. Asking for a profile that does not exist is a configuration error (exit 2) that "
        f"names the ones that do: {tool_profiles.names_sentence()}.",
        "",
        "## What a profile is, and what it is not",
        "",
        "- A profile is a **literal set of tool names**, not a prefix rule. `cluster_debug_workload` and "
        "`cluster_posture_scan` share a prefix and sit in different profiles.",
        "- A profile is **intersected with what this configuration offers**. `incident` names the live-cluster "
        "tools; a server started without `cluster.enabled` offers none of them, and the profile is what is left "
        "rather than a promise the server cannot keep.",
        "- A tool the profile leaves out is **not an unknown tool**. `tools/list` is the profile, but a "
        "`tools/call` for an excluded tool answers with an error that says the tool exists, names the profiles "
        "that hold it and gives the flag that offers it. A client told a real capability does not exist stops "
        "asking for it.",
        "- The profile is stated in the server's `initialize` response, so a client can see which surface it got "
        "without comparing counts. The server's instructions name about thirty tools in prose; that sentence also "
        "names the ones the profile withholds, so the first thing a client reads does not send it after a tool it "
        "cannot call.",
        "- `kubenoob_config_status` is in every profile and reports the profile, the tools it offers and, by name, "
        "the tools of this configuration that it does not.",
        "- It narrows the **MCP tool surface only**. The per-tool REST routes of `kube-noob serve` are addressed "
        "by path, cost a client no context, and are not narrowed.",
        "",
        "## The profiles",
        "",
        "| Profile | Tools (default configuration) | Tools (every surface on) | For |",
        "|---|---|---|---|",
    ]
    for name in tool_profiles.NAMES:
        held_default = len(tool_profiles.select(name, default))
        held_all = len(tool_profiles.select(name, everything))
        lines.append(f"| `{name}` | {held_default} | {held_all} | {tool_profiles.SUMMARIES[name]} |")
    lines += [
        "",
        "Every profile carries `config_status` (what this server will and will not do), `search_knowledge` and "
        "`get_knowledge` (the store the server's instructions require every factual claim to cite).",
        "",
    ]
    for name in named:
        tools = sorted(tool_profiles.PROFILES[name])
        lines += [
            f"### `--tools {name}`",
            "",
            tool_profiles.SUMMARIES[name],
            "",
            "| Tool | What it does | In this configuration |",
            "|---|---|---|",
        ]
        for tool in tools:
            where = (
                "default"
                if tool in default
                else ("only with its surface enabled" if tool in everything else "not in any configuration")
            )
            title = everything.get(tool, "")
            lines.append(f"| `{TOOL_PREFIX}{tool}` | {title} | {where} |")
        lines.append("")
    outside = sorted(set(everything) - set().union(*(tool_profiles.PROFILES[n] for n in named)))
    lines += [
        "## Tools in no named profile",
        "",
        (
            "None: every tool belongs to at least one profile, and "
            "`tests/test_tool_profiles.py::test_every_tool_that_can_exist_is_in_at_least_one_named_profile` fails "
            "when a new one does not."
            if not outside
            else "Only `--tools all` offers these: " + ", ".join(f"`{TOOL_PREFIX}{t}`" for t in outside) + "."
        ),
        "",
        "## The bundled Claude plugin",
        "",
        "`plugin/kube-noob` sets `KUBE_NOOB_MCP_TOOLS=all` and keeps it there. Its seven skills name tools from "
        "three different profiles, so any narrower default would have those skills call tools their own server "
        "does not offer -- the same absence-as-no-such-thing defect, one layer up. "
        "`tests/test_tool_profiles.py::test_the_bundled_plugin_stays_on_all_because_its_skills_span_the_surface` "
        "holds that. `plugin/kube-noob-skills`, the directory plugin, drives the installed CLI and starts no MCP "
        "server, so it names no profile.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="exit 1 when the document is stale")
    a = ap.parse_args(argv)
    body = render()
    if a.check:
        current = DOC.read_text(encoding="utf-8") if DOC.is_file() else ""
        if current != body:
            print(f"{DOC.relative_to(ROOT)} is stale: run python scripts/tool_profiles_doc.py")
            return 1
        print(f"{DOC.relative_to(ROOT)} matches kube_noob.tool_profiles and the tool surface")
        return 0
    DOC.write_text(body, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
