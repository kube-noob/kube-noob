#!/usr/bin/env python3
"""Generate ``docs/false-pass-benchmark.md`` from the corpus under ``tests/falsepass/cases``.

The benchmark (G282, ``tests/test_false_pass_benchmark.py``) is the product's one rule turned into a gate: an
absence, an unknown or an unrecognised shape never reads as a pass. This document is its index -- every case by
defect class, with the command it drives, the verdict the input decides, the false pass it refuses and where it was
found -- so a reader can see what the corpus holds without running it, and a contributor adding a case sees the
shape to copy.

The document is generated from the case files and nothing else: no case is run, so the tables change only when
the corpus does. Whether a case waiting for a branch enforces today is decided at run time by its probe, and the
test's own summary table (printed at the end of a pytest session) says which do; this document lists the branch
each one waits for, which is static.

    python scripts/false_pass_report.py --check    # exit 1 when the document is stale
    python scripts/false_pass_report.py            # rewrite it
    python scripts/false_pass_report.py --table    # the Markdown tables alone, on stdout
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT))

from tests.falsepass import harness as fp  # noqa: E402

from kube_noob import sanitize  # noqa: E402

DOC = ROOT / "docs" / "false-pass-benchmark.md"

HEADER = """# The false-pass benchmark

<!-- Generated by scripts/false_pass_report.py from tests/falsepass/cases; do not edit by hand. -->

**The rule, held for every input in this corpus:** an absence, an unknown or an unrecognised shape never reads
as a pass. What was not read, could not
be parsed, was cut by a cap, came back refused, or arrived in a shape the code does not model is part of the answer
-- `not determined`, `undetermined`, `not evaluated`, `partial` -- in the text view, in JSON and YAML, and in the
MCP tool result. It is never `allowed`, `complete: true`, `none`, `mitigated` or exit 0.

Two days of adversarial review before merge found about 250 defects, and most of them had that one shape: a false
pass. The reproducers lived in scratch directories; this corpus keeps them. Each case under `tests/falsepass/cases/`
holds the input (small; anything larger is generated in code), the command line and, where one exists, the MCP tool
and its arguments, the verdict class the input decides, the forbidden outcome as it was observed, the defect class
from the builder brief and where the case was found. `tests/test_false_pass_benchmark.py` runs every case through
the real CLI (a subprocess, `-I`, no network, a fixed environment, the same bytes twice) and the in-process tool,
and fails when a forbidden outcome appears or the expected one does not. The table it prints at the end of a
session says, per class and per source branch, how many cases enforce today, how many wait for a merge, and how
many failed.

A case found on a branch that has not merged carries `expected_on` and a `probe` (a module, a command or a string
in a source file that the merge brings). Until the probe holds the case is run, its outcome recorded and printed,
and it does not fail the suite; the day the branch merges the probe holds and the case enforces, with no edit to
the corpus. A test holds that a case whose branch is an ancestor of HEAD has a satisfied probe, so a case cannot
wait forever after a merge; a squash merge leaves no ancestor, which is the residual gap, and a case is then only
as good as its probe. Probes are observables where one exists (a command the parser accepts, a key in the JSON of a
tiny run); the seven live `policy reach` cases and the two text-view injection cases probe a source string, because
no offline run shows the live classifier or a renderer's output boundary. A case marked `expected_on: main` is a
known-failing case (the false pass is open on main and nobody's branch fixes it yet); it is counted as waiting, never
weakened, and listed under open questions. A case is never weakened to pass.

**Adding a case** when you find a false pass: copy a neighbouring file in `tests/falsepass/cases/`, put the input
under `tests/falsepass/inputs/<name>/` byte for byte (name anything that looks like an instruction `injection*`),
write the command, the `expect` that the honest answer must show and the `forbid` that the false pass showed, give
it the defect class number and one line of provenance, and run `pytest tests/test_false_pass_benchmark.py -k
<name>`. Then regenerate this page: `python scripts/false_pass_report.py`.

"""

CLASS_TABLE = """## Cases by defect class

| Class | Shape | Cases | On main | Waiting for a merge |
|---|---|---|---|---|
"""

#: Why a defect class has no case here: it is not a shape a command's output shows, and other tests hold it.
HELD_ELSEWHERE = {
    8: "a documentation claim is not something a command's output shows; `tests/test_doc_claims.py` and the "
    "guidance row check hold those",
    10: "a property of the test suite, not of a verdict; CI runs the suite on four Python versions",
    12: "a run past the harness's time bound (120 s) fails its case, so a quadratic loop inside a cap is a finding "
    "wherever a case reaches it; no case is filed under this class on purpose, because the cost shows up on the "
    "case that pays it",
    18: "not a verdict shape; it belongs with the tests of the writer that mints the name",
    19: "needs a running server with a clock; this runner is offline and drives one process at a time",
    20: "a chart property, outside what a command's output shows",
}

BRANCH_TABLE = """## Cases by source

| Source | Cases | Classes |
|---|---|---|
"""


def _cell(text: str) -> str:
    """One Markdown cell from case text: made printable by Unicode category (the summaries describe hostile input
    and may quote it), whitespace collapsed, the table delimiter escaped."""
    return " ".join(sanitize.visible(text).split()).replace("|", "\\|")


def tables(cases: list[fp.Case]) -> str:
    out = [CLASS_TABLE]
    for n, shape in fp.DEFECT_CLASSES.items():
        group = [c for c in cases if c.defect_class == n]
        if not group:
            out.append(f"| {n} | {shape} | 0 | 0 | 0 |\n")
            continue
        waiting = sum(1 for c in group if c.expected_on)
        out.append(f"| {n} | {shape} | {len(group)} | {len(group) - waiting} | {waiting} |\n")
    out.append(f"| | **total** | **{len(cases)}** | **{sum(1 for c in cases if not c.expected_on)}** | ")
    out.append(f"**{sum(1 for c in cases if c.expected_on)}** |\n\n")
    empty = [n for n in fp.DEFECT_CLASSES if not any(c.defect_class == n for c in cases)]
    if empty:
        out.append("Classes with no case, and where the shape is held instead:\n\n")
        for n in empty:
            why = HELD_ELSEWHERE.get(n, "no reproducer has been captured yet")
            out.append(f"- class {n} ({fp.DEFECT_CLASSES[n]}): {why}\n")
        out.append("\n")
    out.append(BRANCH_TABLE)
    for source in sorted({c.expected_on or "main" for c in cases}, key=lambda s: (s != "main", s)):
        group = [c for c in cases if (c.expected_on or "main") == source]
        classes = ", ".join(str(k) for k in sorted(Counter(c.defect_class for c in group)))
        out.append(f"| `{source}` | {len(group)} | {classes} |\n")
    return "".join(out)


def listing(cases: list[fp.Case]) -> str:
    out = ["\n## The cases\n"]
    for n, shape in fp.DEFECT_CLASSES.items():
        group = [c for c in cases if c.defect_class == n]
        if not group:
            continue
        out.append(f"\n### Class {n}: {shape}\n\n")
        for c in group:
            wait = ""
            if c.expected_on == "main":
                wait = " -- known failing on main"
            elif c.expected_on:
                wait = f" -- waits for `{c.expected_on}`"
            argv = " ".join(c.argv)
            tool = f"; tool `{c.mcp_tool}`" if c.mcp_tool else ""
            out.append(f"- **`{c.id}`** ({c.verdict_class}{wait})\n")
            out.append(f"  - {_cell(c.summary)}\n")
            out.append(f"  - `kube-noob {_cell(argv)}`{tool}\n")
            out.append(f"  - forbidden: {_cell(c.forbidden_what)}\n")
            out.append(f"  - found: {_cell(c.provenance)}\n")
    return "".join(out)


def render(cases: list[fp.Case]) -> str:
    return HEADER + tables(cases) + listing(cases)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when the document is stale")
    parser.add_argument("--table", action="store_true", help="print the Markdown tables and exit")
    args = parser.parse_args(argv)
    cases = fp.load_cases()
    if args.table:
        sys.stdout.write(tables(cases))
        return 0
    text = render(cases)
    if args.check:
        current = DOC.read_text("utf-8") if DOC.is_file() else ""
        if current != text:
            print(f"{DOC.relative_to(ROOT)} is stale: run python scripts/false_pass_report.py", file=sys.stderr)
            return 1
        print(f"{DOC.relative_to(ROOT)} matches the corpus ({len(cases)} cases)")
        return 0
    DOC.write_text(text, "utf-8")
    print(f"wrote {DOC.relative_to(ROOT)} ({len(cases)} cases)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
